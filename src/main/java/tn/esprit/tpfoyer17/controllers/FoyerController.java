package tn.esprit.tpfoyer17.controllers;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.experimental.FieldDefaults;
import lombok.extern.slf4j.Slf4j;
import org.springframework.web.bind.annotation.*;
import tn.esprit.tpfoyer17.dto.FoyerDTO;
import tn.esprit.tpfoyer17.entities.Foyer;
import tn.esprit.tpfoyer17.services.IFoyerService;

import java.util.List;

@RestController
@AllArgsConstructor
@Slf4j
@FieldDefaults(level = AccessLevel.PRIVATE)
@RequestMapping("api/foyers")
public class FoyerController {
    IFoyerService foyerService;

    @PostMapping("add")
    public Foyer addingFoyer(@RequestBody FoyerDTO dto){
        return foyerService.addFoyer(nouveauFoyer(dto));
    }
    @GetMapping("getAll")
    public List<Foyer> gettingAllFoyer(){
        return foyerService.getAllFoyers();
    }

    @GetMapping("get")
    public Foyer gettingFoyer(@RequestParam("idFoyer") long idFoyer){
        return foyerService.getFoyerById(idFoyer);
    }

    @DeleteMapping("delete/{idFoyer}")
    public void deletingFoyer(@PathVariable("idFoyer") long idFoyer){
        foyerService.deleteFoyer(idFoyer);
    }

    @PutMapping("update")
    public Foyer updatingFoyer(@RequestBody FoyerDTO dto){
        if (dto.idFoyer() == null) {
            throw new IllegalArgumentException("idFoyer est obligatoire pour une mise a jour");
        }
        // Start from the foyer stored in the database (404 if unknown), never from the client's object
        Foyer foyer = foyerService.getFoyerById(dto.idFoyer());
        foyer.setNomFoyer(dto.nomFoyer());
        foyer.setCapaciteFoyer(dto.capaciteFoyer());
        return foyerService.updateFoyer(foyer);
    }
    @PostMapping("ajouter-affecter")
    public Foyer ajouterFoyerEtAffecterAUniversite (@RequestBody FoyerDTO dto, @RequestParam("idUniversite") long idUniversite){
        return foyerService.ajouterFoyerEtAffecterAUniversite(nouveauFoyer(dto),idUniversite);
    }

    private Foyer nouveauFoyer(FoyerDTO dto) {
        // Only the allowed fields are copied: the id is generated by the database
        return Foyer.builder().nomFoyer(dto.nomFoyer()).capaciteFoyer(dto.capaciteFoyer()).build();
    }

}
