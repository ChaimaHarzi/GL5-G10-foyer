package tn.esprit.tpfoyer17.controllers;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.experimental.FieldDefaults;
import lombok.extern.slf4j.Slf4j;
import org.springframework.web.bind.annotation.*;
import tn.esprit.tpfoyer17.dto.BlocDTO;
import tn.esprit.tpfoyer17.entities.Bloc;
import tn.esprit.tpfoyer17.entities.Foyer;
import tn.esprit.tpfoyer17.services.IBlocService;

import java.util.List;

@RestController
@AllArgsConstructor
@Slf4j
@FieldDefaults(level = AccessLevel.PRIVATE)
@RequestMapping("api/blocs")
@Tag(name = "Gestion des Blocs",description = "les apis pour gérer tout les Bloc")
public class BlocController {
    IBlocService blocService;

    // Order 1
    @Operation(description = "methode pour ajouter des blocs",summary = "ajouter un bloc",operationId = "1")
    @PostMapping("add")
    public Bloc addingBloc(@RequestBody BlocDTO dto){
        // Only the allowed fields are copied: the id is generated by the database
        Bloc bloc = Bloc.builder()
                .nomBloc(dto.nomBloc())
                .capaciteBloc(dto.capaciteBloc())
                .foyer(dto.idFoyer() == null ? null : Foyer.builder().idFoyer(dto.idFoyer()).build())
                .build();
        return blocService.addBloc(bloc);
    }

    // Order 2
    @GetMapping("getAll")
    public List<Bloc> gettingAllBloc(){
        return blocService.getAllBlocs();
    }

    // Order 3
    @GetMapping("get")
    public Bloc gettingBloc(@RequestParam("idBloc") long idBloc){
        return blocService.getBlocById(idBloc);
    }

    // Order 4
    @DeleteMapping("delete/{idBloc}")
    public void deletingBloc(@PathVariable("idBloc") long idBloc){
        blocService.deleteBloc(idBloc);
    }

    // Order 5
    @PutMapping("update")
    public Bloc updatingBloc(@RequestBody BlocDTO dto){
        if (dto.idBloc() == null) {
            throw new IllegalArgumentException("idBloc est obligatoire pour une mise a jour");
        }
        // Start from the bloc stored in the database (404 if unknown), never from the client's object
        Bloc bloc = blocService.getBlocById(dto.idBloc());
        bloc.setNomBloc(dto.nomBloc());
        bloc.setCapaciteBloc(dto.capaciteBloc());
        bloc.setFoyer(dto.idFoyer() == null ? null : Foyer.builder().idFoyer(dto.idFoyer()).build());
        return blocService.updateBloc(bloc);
    }

    // Order 6
    @PutMapping("affecter-chambre-bloc")
    public Bloc affecterChambresABloc(@RequestBody List<Long> numChambre,@RequestParam("idBloc") long idBloc){
        return blocService.affecterChambresABloc(numChambre,idBloc);
    }




}
